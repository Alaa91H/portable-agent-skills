#!/usr/bin/env bash
#
# build-catalog-doc.sh - generate docs/catalog.md from the canonical skills.
#
# The catalog is documentation, and documentation drifts. Generating it from the
# source means the routing sentences in the table can never disagree with the
# descriptions that actually ship. Cluster membership comes from
# skills.sh.json, which is the single place a skill is assigned to a category.
#
# Usage: scripts/build-catalog-doc.sh [--check]

set -uo pipefail

CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || exit 2

SRC=".opencode/skills"
OUT="docs/catalog.md"
# Not GROUPS: bash reserves that name for the caller's group id list and
# silently ignores an assignment to it.
GROUPS_FILE="skills.sh.json"

if [ -t 1 ]; then
  RED=$'\033[31m'; GRN=$'\033[32m'; BLD=$'\033[1m'; RST=$'\033[0m'
else
  RED=''; GRN=''; BLD=''; RST=''
fi

[ -d "$SRC" ] || { printf 'error: %s not found\n' "$SRC" >&2; exit 2; }
[ -f "$GROUPS_FILE" ] || { printf 'error: %s not found\n' "$GROUPS_FILE" >&2; exit 2; }

fm_get() {
  awk -v key="$2" '
    { sub(/\r$/, "") }
    NR == 1 { sub(/^\xef\xbb\xbf/, ""); if ($0 != "---") exit; next }
    $0 == "---" { exit }
    index($0, key ":") == 1 {
      v = substr($0, length(key) + 2)
      sub(/^[ \t]+/, "", v); sub(/[ \t]+$/, "", v)
      if (v ~ /^[|>][-+]?$/) { inblock = 1; blk = ""; next }
      if (substr(v, 1, 1) == "\"") v = substr(v, 2)
      if (length(v) && substr(v, length(v), 1) == "\"") v = substr(v, 1, length(v) - 1)
      print v; exit
    }
    inblock {
      if ($0 ~ /^[ \t]/ || $0 == "") { t = $0; sub(/^[ \t]+/, "", t); blk = blk (blk == "" ? "" : " ") t; next }
      print blk; exit
    }
  ' "$1"
}

count=0
for d in "$SRC"/*/; do [ -f "$d/SKILL.md" ] && count=$((count + 1)); done
listed=0
missing=0

tmp="$OUT.tmp.$$"

# The temporary file is removed on the way out, whatever happens. Without this
# a run that is interrupted between creating the temporary file and renaming it
# leaves the temporary file behind, and the next `git add -A` commits it. That
# is not hypothetical: docs/catalog.md.tmp.808 was committed to this repository
# and sat in the tree for a release, because the run that created it was
# interrupted and the file was picked up by the next commit.
#
# After a successful rename the temporary file no longer exists and the trap
# is a no-op, so it costs nothing in the normal path.
#
# EXIT alone is not enough. A signal that is not trapped terminates the shell
# without running the EXIT trap, so TERM and INT are trapped explicitly. A
# SIGKILL cannot be trapped by anything, which is why scripts/check-repo-state.sh
# also fails the build when a temporary file is found in the tree: the gate is
# the protection, and the trap is only tidiness.
cleanup_tmp() { rm -f "$tmp"; }
trap cleanup_tmp EXIT
trap cleanup_tmp TERM
trap cleanup_tmp INT

{
  cat <<'HEADER'
# Catalog

This file is generated by `scripts/build-catalog-doc.sh` from
`.opencode/skills/` and `skills.sh.json`. Do not edit it by hand; edit the
skill's frontmatter or its cluster assignment and regenerate.

Read `authoring.md` before adding or changing any of these.

The routing sentence is the skill's exact `description`. Changing it changes when
the agent reaches for the skill, so treat it as reviewed surface rather than
incidental wording.

HEADER
  printf '%s skills, grouped by cluster.\n\n' "$count"

  # Cluster tables. Membership lives only in skills.sh.json, so a skill has
  # exactly one home. Matching is on the 8-space skill entries inside each
  # "skills" array, and anything that does not resolve to a directory is
  # reported rather than silently dropped.
  clusters=0
while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      *'"title"'*)
        t="$(printf '%s' "$line" | sed -e 's/^[[:space:]]*"title":[[:space:]]*"//' -e 's/",\?[[:space:]]*$//')"
        printf '\n## %s\n\n' "$t"
        clusters=$((clusters + 1))
        ;;
      *'"description"'*)
        d="$(printf '%s' "$line" | sed -e 's/^[[:space:]]*"description":[[:space:]]*"//' -e 's/",\?[[:space:]]*$//')"
        printf '%s\n\n' "$d"
        printf '| Skill | Routes when |\n| --- | --- |\n'
        ;;
      '        "'*)
        name="$(printf '%s' "$line" | sed -e 's/^[[:space:]]*"//' -e 's/",\?[[:space:]]*$//')"
        case "$name" in
          ''|*[!a-z0-9-]*) continue ;;        # not a skill id
        esac
        f="$SRC/$name/SKILL.md"
        if [ ! -f "$f" ]; then
          printf '| `%s` | **listed in skills.sh.json but the skill is missing** |\n' "$name"
          missing=$((missing + 1))
          continue
        fi
        printf '| `%s` | %s |\n' "$name" "$(fm_get "$f" description)"
        listed=$((listed + 1))
        ;;
    esac
  done < "$GROUPS_FILE"

  cat <<'FOOTER'

---

## Provenance

Each skill was written from published guidance rather than invented. The document
skills and the engineering post are Anthropic's; `superpowers` and
`skill-creator` are the most-installed community collections and supplied the
description and token-budget findings.

- Open Agent Skills specification — <https://agentskills.io/specification>
- OpenCode V2 skills — <https://opencode.ai/v2/docs/skills>
- Anthropic, *Equipping agents for the real world with Agent Skills* —
  <https://www.anthropic.com/engineering/equipping-agents-for-the-real-world-with-agent-skills>
- Anthropic official skills — <https://github.com/anthropics/skills>
- `obra/superpowers` — <https://github.com/obra/superpowers>
- Agent Skills platform documentation —
  <https://platform.claude.com/docs/en/agents-and-tools/agent-skills/best-practices>
- `trailofbits/skills` — <https://github.com/trailofbits/skills>
- `vercel-labs/agent-skills` — <https://github.com/vercel-labs/agent-skills>
- OWASP Cheat Sheet Series — <https://cheatsheetseries.owasp.org/>
- Google SRE Workbook — <https://sre.google/workbook/>
- Kubernetes documentation — <https://kubernetes.io/docs/>
- Kafka design documentation — <https://kafka.apache.org/documentation/>
- RFC 9457 Problem Details — <https://www.rfc-editor.org/rfc/rfc9457.html>
- OAuth 2.1 — <https://oauth.net/2.1>

## Naming

Names here deliberately avoid `helper`, `utils` and `tools`. Those describe a role
rather than a situation, so they never tell an agent when to load the skill.
FOOTER
} > "$tmp"

if [ -f "$OUT" ] && cmp -s "$tmp" "$OUT"; then
  rm -f "$tmp"
  if [ "$CHECK" -eq 1 ]; then
    printf '%scatalog.md is up to date%s\n' "$GRN" "$RST"
    exit 0
  fi
  printf 'nothing to do, %s catalog.md is current%s\n' "$GRN" "$RST"
  exit 0
fi

if [ "$CHECK" -eq 1 ]; then
  printf '%scatalog.md is out of date%s - run scripts/build-catalog-doc.sh\n' "$RED" "$RST"
  rm -f "$tmp"
  exit 1
fi

if [ "$missing" -gt 0 ]; then
  printf '%swrote %s (%d of %d skills; %d listed but missing)%s\n' "$RED" "$OUT" "$listed" "$count" "$missing" "$RST"
  exit 1
fi

if [ "$listed" -ne "$count" ]; then
  printf '%swrote %s but %d skill(s) are unassigned; add them to %s%s\n' \
    "$RED" "$OUT" "$((count - listed))" "$GROUPS_FILE" "$RST"
  exit 1
fi

mv "$tmp" "$OUT"
printf '%swrote %s (%d skills, %d clusters)%s\n' "$GRN" "$OUT" "$count" "$clusters" "$RST"
exit 0